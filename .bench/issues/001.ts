import { sim } from '../sim.ts'

const t = sim({ title: '001 writer が 2 つのとき、merge と push の交差で保存済みの変更が消える' })
const a = t.node('A')
const b = t.node('B')
const v = t.client('u2', b)

await t.note('2 chunk 以上の image を作り、同じ store を A と B が開く')
await t.state({ chunks: 2 })
await a.open()
await b.open()
await t.note('形 1: B が push に成功する。その push を知らない A が merge する')
await v.cell('p', 1, 'a', 'saved by B')
await b.save()
await a.fill('p', 'a', 1200, 2000)
await a.save()
await a.expect({ axis: 'writer', known: '001', error: 'store conflict' })
await t.replica(1).expect({ axis: 'writer', known: '001', exists: true, linked: true })
await t.note('形 2: A が merge に成功した。その merge を知らない B が push する')
await v.cell('p', 1, 'a', 'saved by B again')
await b.save()
await b.expect({ axis: 'writer', known: '001', error: 'store conflict' })
await t.note('開き直すと、B が成功と受け取った save の内容は無い')
await a.open()
await a.expect({ axis: '永続', known: '001', sql: 'select "a" from "p" where "_id" = 1', rows: [['saved by B again']] })

export default await t.done()
