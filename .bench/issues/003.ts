import { sim } from '../sim.ts'

const t = sim({ title: '003 put が書いた後に reject すると、その node は開き直すまで save できない' })
const a = t.node('A')
const u = t.client('u1', a)
const count = 'select count(*) from "p"'

await t.note('5 chunk の image を作って保存する')
await a.open()
await a.run({ type: 'page.add', page: 'p' })
await a.run({ type: 'col.add', page: 'p', col: 'a' })
await a.fill('p', 'a', 4400, 2000)
await a.save()
await t.note('次の save の put は、store に書いた後に reject する')
await a.fill('p', 'a', 1200, 2000)
await t.store.fail('put.after')
await a.save()
await a.expect({ axis: '永続', known: '003', error: 'injected put after write', store: [0] })
await t.note('期待: 編集も save も読みも通る')
await u.cell('p', 1, 'a', 'lost')
await a.save()
await a.expect({ axis: '可用', known: '003', error: '' })
await a.run({ type: 'sql', text: count })
await a.expect({ axis: '可用', known: '003', error: '' })
await t.note('開き直すと、reject した save の内容 (5,600 行) で続行できる。その後の編集は無い')
await a.open()
await a.expect({ axis: '永続', sql: count, rows: [[5600]] })
await a.expect({ axis: '永続', sql: `select count(*) from "p" where "a" = 'lost'`, rows: [[0]] })

export default await t.done()
