import { sim } from '../sim.ts'

const t = sim({ title: '作り直した node の最初の open が get の失敗で reject した後に、命令を送る' })
const a = t.node('A')

await a.open()
await a.run({ type: 'page.add', page: 'p' })
await a.run({ type: 'col.add', page: 'p', col: 'a' })
await a.run({ type: 'row.add', page: 'p' })
await a.save()
await t.note('作り直しの後の open の get が失敗する')
await a.stop()
await t.store.fail('get')
await a.open()
await a.expect({ axis: '原子', error: 'injected get' })
await t.note('開いていない node への命令は reject し、save は store を呼ばずに解決する (contract.md 3 節)')
await a.run({ type: 'row.add', page: 'p' })
await a.expect({ axis: '原子', error: true })
await a.save()
await a.expect({ axis: '原子', error: '', calls: 0 })
await t.note('開き直すと、保存済みの内容で続行できる')
await a.open()
await a.expect({ axis: '原子', sql: 'select count(*) from "p"', rows: [[1]] })

export default await t.done()
