import { sim } from '../sim.ts'

const t = sim({ title: 'store の呼び出しの途中で node を失う。進行中の put は、届くことも届かないこともある' })
const a = t.node('A')
const b = t.node('B')
const u = t.client('u1', a)
const v = t.client('u1', b)
const count = (text: string) => `select count(*) from "p" where "a" = '${text}'`

await a.open()
await a.run({ type: 'page.add', page: 'p' })
await a.run({ type: 'col.add', page: 'p', col: 'a' })
await a.fill('p', 'a', 1200, 2000)
await a.save()
await t.note('push の put を store の手前で止め、node を失う。put は届かない')
await u.cell('p', 1, 'a', 'never arrives')
await t.store.hold()
await a.save()
await a.stop()
await t.store.release('lose')
await a.open()
await a.expect({ axis: '原子', sql: count('never arrives'), rows: [[0]] })
await t.note('同じことをして、put は届く')
await u.cell('p', 1, 'a', 'arrives late')
await t.store.hold()
await a.save()
await a.stop()
await t.store.release('arrive')
await a.open()
await a.expect({ axis: '原子', sql: count('arrives late'), rows: [[1]], store: [0, 1] })
await t.note('古い node の put が途中のまま、新しい node が同じ store を開いて書く。後から届いた put は入らない')
await u.cell('p', 1, 'a', 'old writer')
await t.store.hold()
await a.save()
await b.open()
await v.cell('p', 1, 'a', 'new writer')
await b.save()
await t.store.release('arrive')
await a.expect({ axis: 'writer', error: 'store conflict' })
await a.stop()
await b.expect({ axis: 'writer', sql: count('new writer'), rows: [[1]], store: [0, 1, 2] })

export default await t.done()
